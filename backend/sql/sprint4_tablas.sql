-- ==========================================================
-- SPRINT 4 · TABLAS NUEVAS (Oracle)
--   #29 Auditoría y logs de transacciones  → AUDITORIA
--   #28 Feedback y reporte de fallos       → FEEDBACK
-- Ejecutar UNA sola vez, conectado como el dueño del esquema
-- (ADMIN), o desde la carpeta backend con:  npm run crear-tablas
--
-- Estas tablas NO tienen claves foráneas a propósito: el
-- historial de auditoría y los reportes deben conservarse
-- aunque un usuario o un producto cambien o se eliminen
-- (guardan una "foto" del nombre de usuario).
-- ==========================================================

CREATE TABLE auditoria (
  id_auditoria  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha         TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  id_usuario    NUMBER,
  usuario       VARCHAR2(50),
  rol           VARCHAR2(20),
  accion        VARCHAR2(40) NOT NULL,
  entidad       VARCHAR2(30),
  id_entidad    VARCHAR2(40),
  resultado     VARCHAR2(10) DEFAULT 'EXITO' NOT NULL,
  detalle       VARCHAR2(500),
  ip            VARCHAR2(45),
  CONSTRAINT chk_resultado_audit CHECK (resultado IN ('EXITO', 'FALLO'))
);

CREATE INDEX idx_auditoria_fecha ON auditoria (fecha);
CREATE INDEX idx_auditoria_usuario ON auditoria (usuario);

CREATE TABLE feedback (
  id_feedback       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha             TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  id_usuario        NUMBER,
  usuario           VARCHAR2(50),
  tipo              VARCHAR2(15) NOT NULL,
  gravedad          VARCHAR2(10),
  titulo            VARCHAR2(100) NOT NULL,
  descripcion       VARCHAR2(1000) NOT NULL,
  pantalla          VARCHAR2(30),
  origen            VARCHAR2(10) DEFAULT 'MANUAL' NOT NULL,
  estado            VARCHAR2(15) DEFAULT 'ABIERTO' NOT NULL,
  fecha_resolucion  TIMESTAMP,
  CONSTRAINT chk_tipo_feedback CHECK (tipo IN ('FALLO', 'SUGERENCIA', 'COMENTARIO')),
  CONSTRAINT chk_gravedad_feedback CHECK (gravedad IS NULL OR gravedad IN ('BAJA', 'MEDIA', 'ALTA')),
  CONSTRAINT chk_origen_feedback CHECK (origen IN ('MANUAL', 'AUTOMATICO')),
  CONSTRAINT chk_estado_feedback CHECK (estado IN ('ABIERTO', 'EN_REVISION', 'RESUELTO'))
);

CREATE INDEX idx_feedback_estado ON feedback (estado);
CREATE INDEX idx_feedback_usuario ON feedback (id_usuario);
