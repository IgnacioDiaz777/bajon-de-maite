-- Datos de contacto del cliente (CLIENTE solo guarda el nombre)
CREATE TABLE cliente_perfil (
  id_cliente           NUMBER PRIMARY KEY,
  telefono             VARCHAR2(20),
  email                VARCHAR2(100),
  notas                VARCHAR2(300),
  fecha_actualizacion  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_perfil_cliente FOREIGN KEY (id_cliente) REFERENCES cliente (id_cliente)
);

-- Direcciones de despacho (un cliente puede tener varias; una es la principal)
CREATE TABLE direccion_despacho (
  id_direccion    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_cliente      NUMBER NOT NULL,
  alias           VARCHAR2(30) NOT NULL,
  calle           VARCHAR2(80) NOT NULL,
  numero          VARCHAR2(15) NOT NULL,
  depto           VARCHAR2(20),
  comuna          VARCHAR2(40) NOT NULL,
  ciudad          VARCHAR2(40) DEFAULT 'Santiago' NOT NULL,
  referencia      VARCHAR2(150),
  es_principal    NUMBER(1) DEFAULT 0 NOT NULL,
  activa          NUMBER(1) DEFAULT 1 NOT NULL,
  fecha_creacion  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_direccion_cliente FOREIGN KEY (id_cliente) REFERENCES cliente (id_cliente),
  CONSTRAINT chk_direccion_principal CHECK (es_principal IN (0, 1)),
  CONSTRAINT chk_direccion_activa CHECK (activa IN (0, 1))
);

CREATE INDEX idx_direccion_cliente ON direccion_despacho (id_cliente);

-- Pagos de los pedidos (en efectivo o con tarjeta por Webpay).
-- Nunca se guardan datos de la tarjeta: solo los últimos 4 dígitos que informa la pasarela.
CREATE TABLE pago (
  id_pago              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_pedido            NUMBER NOT NULL,
  metodo               VARCHAR2(10) NOT NULL,
  proveedor            VARCHAR2(10) NOT NULL,
  monto                NUMBER(12) NOT NULL,
  estado               VARCHAR2(15) DEFAULT 'CREADO' NOT NULL,
  buy_order            VARCHAR2(26),
  token                VARCHAR2(100),
  codigo_autorizacion  VARCHAR2(20),
  codigo_respuesta     NUMBER(4),
  tipo_tarjeta         VARCHAR2(5),
  ultimos4             VARCHAR2(4),
  cuotas               NUMBER(3),
  monto_reembolsado    NUMBER(12) DEFAULT 0 NOT NULL,
  id_usuario           NUMBER,
  usuario              VARCHAR2(50),
  detalle              VARCHAR2(300),
  fecha_creacion       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  fecha_actualizacion  TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_pago_pedido FOREIGN KEY (id_pedido) REFERENCES pedido (id_pedido),
  CONSTRAINT uq_pago_buy_order UNIQUE (buy_order),
  CONSTRAINT uq_pago_token UNIQUE (token),
  CONSTRAINT chk_pago_metodo CHECK (metodo IN ('EFECTIVO', 'WEBPAY')),
  CONSTRAINT chk_pago_proveedor CHECK (proveedor IN ('MANUAL', 'SIMULADO', 'TRANSBANK')),
  CONSTRAINT chk_pago_monto CHECK (monto > 0),
  CONSTRAINT chk_pago_estado CHECK (estado IN ('CREADO', 'CONFIRMANDO', 'AUTORIZADO', 'RECHAZADO', 'ANULADO', 'EXPIRADO', 'ABANDONADO'))
);

CREATE INDEX idx_pago_pedido ON pago (id_pedido);
CREATE INDEX idx_pago_estado ON pago (estado, fecha_creacion);

-- Un pedido solo puede tener UN pago autorizado (evita cobrar dos veces aunque dos cajeros hagan clic a la vez).
-- Oracle no indexa los NULL, así que esto solo aplica a las filas con estado AUTORIZADO.
CREATE UNIQUE INDEX uq_pago_un_autorizado ON pago (CASE WHEN estado = 'AUTORIZADO' THEN id_pedido END);
